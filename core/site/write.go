package site

import (
	"bytes"
	"compress/gzip"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path"
	"sort"
	"strings"
)

// MarkerFile identifies a directory as a generated site output. Write only clears stale
// files from directories that carry it, so a mistyped --out can never wipe real data.
const MarkerFile = ".can-site"

// WriteOptions control Write.
type WriteOptions struct {
	// Force allows writing into a non-empty directory that was not produced by this tool. Generated
	// paths are overwritten, but nothing else in the directory is ever deleted.
	Force bool
	// Compress also writes <file>.gz next to text files for servers that serve precompressed content.
	Compress bool
}

var compressible = map[string]bool{".html": true, ".css": true, ".xml": true, ".txt": true, ".svg": true, ".json": true}

func gzipBytes(b []byte) ([]byte, error) {
	var buf bytes.Buffer
	zw, err := gzip.NewWriterLevel(&buf, gzip.BestCompression)
	if err != nil {
		return nil, err
	}
	// The zero-value header (no name, zero mtime) keeps the output reproducible.
	if _, err := zw.Write(b); err != nil {
		return nil, err
	}
	if err := zw.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// Write publishes the output into dir. Files are replaced one at a time through an atomic
// rename (a server reading the directory never sees a half-written file), the index page is
// written last, and generated files no longer produced (as recorded in the marker) are removed at the end. All file
// operations go through os.Root, so symlinks inside dir cannot redirect them elsewhere.
func (o *Output) Write(dir string, opts WriteOptions) error {
	if err := os.MkdirAll(dir, 0o755); err != nil { //nolint:gosec // the site is public content
		return err
	}
	root, err := os.OpenRoot(dir)
	if err != nil {
		return err
	}
	defer func() { _ = root.Close() }()

	entries, err := fs.ReadDir(root.FS(), ".")
	if err != nil {
		return err
	}
	if _, err := root.Lstat("company.yaml"); err == nil {
		return fmt.Errorf("%s contains company.yaml: refusing to use a company directory as the output directory", dir)
	}
	previous, hadMarker := readMarker(root)
	if len(entries) > 0 && !hadMarker && !opts.Force {
		return fmt.Errorf("%s is not empty and not a site output directory (no %s marker); choose another --out or pass --force", dir, MarkerFile)
	}

	files := make(map[string][]byte, len(o.Files)*2+1)
	for p, b := range o.Files {
		files[p] = b
		if opts.Compress && compressible[strings.ToLower(path.Ext(p))] {
			z, err := gzipBytes(b)
			if err != nil {
				return err
			}
			files[p+".gz"] = z
		}
	}

	order := make([]string, 0, len(files))
	for p := range files {
		order = append(order, p)
	}
	// Referenced assets first, entry pages last, so readers never see a page without its assets.
	rank := func(p string) int {
		switch {
		case strings.HasPrefix(p, "assets/"):
			return 0
		case p == "index.html" || p == "index.html.gz":
			return 2
		}
		return 1
	}
	sort.Slice(order, func(i, j int) bool {
		if ri, rj := rank(order[i]), rank(order[j]); ri != rj {
			return ri < rj
		}
		return order[i] < order[j]
	})
	for _, p := range order {
		if err := writeAtomic(root, p, files[p]); err != nil {
			return err
		}
	}
	// The marker lists every generated path. Only paths listed by the previous build and not
	// generated now are ever deleted; foreign files (even in a marked directory, even with
	// Force) are never touched. A legacy marker without a list deletes nothing.
	if err := writeAtomic(root, MarkerFile, markerContent(order)); err != nil {
		return err
	}
	for _, p := range previous {
		if _, ok := files[p]; !ok {
			if st, err := root.Lstat(p); err != nil || st.IsDir() {
				continue
			}
			if err := root.Remove(p); err != nil && !errors.Is(err, fs.ErrNotExist) {
				return err
			}
			// Tidy directories left empty; a non-empty directory simply fails to be removed.
			for d := path.Dir(p); d != "."; d = path.Dir(d) {
				if root.Remove(d) != nil {
					break
				}
			}
		}
	}
	return nil
}

const markerHeader = "# generated by `can site build`; the paths below are replaced or removed on every build, nothing else is touched\n"

func markerContent(paths []string) []byte {
	sorted := append([]string(nil), paths...)
	sort.Strings(sorted)
	return []byte(markerHeader + strings.Join(sorted, "\n") + "\n")
}

// readMarker returns the paths recorded by the previous build and whether a marker exists.
func readMarker(root *os.Root) ([]string, bool) {
	b, err := root.ReadFile(MarkerFile)
	if err != nil {
		_, statErr := root.Lstat(MarkerFile)
		return nil, statErr == nil
	}
	var paths []string
	for _, line := range strings.Split(string(b), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") || line == MarkerFile || line == "company.yaml" || !fs.ValidPath(line) || line == "." {
			continue
		}
		paths = append(paths, line)
	}
	return paths, true
}

func writeAtomic(root *os.Root, p string, data []byte) error {
	if dir := path.Dir(p); dir != "." {
		if err := root.MkdirAll(dir, 0o755); err != nil { //nolint:gosec // public content
			return err
		}
	}
	tmp := p + ".tmp"
	_ = root.Remove(tmp)
	f, err := root.OpenFile(tmp, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644) //nolint:gosec // public content
	if err != nil {
		return err
	}
	if _, err := f.Write(data); err != nil {
		_ = f.Close()
		_ = root.Remove(tmp)
		return err
	}
	if err := f.Close(); err != nil {
		_ = root.Remove(tmp)
		return err
	}
	if err := root.Rename(tmp, p); err != nil {
		_ = root.Remove(tmp)
		return err
	}
	return nil
}
