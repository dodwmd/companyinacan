// Message returns the text for key with fmt arguments applied. Unknown keys render as the key
// wrapped in !! so they are obvious (a test fails on them).
func (s *Server) msg(key string, args ...any) string {
	m, ok := messagesEN[key]
	if !ok {
		return "!!" + key + "!!"
	}
	if len(args) == 0 {
		return m
	}
	return fmt.Sprintf(m, args...)
}
