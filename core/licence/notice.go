package licence

import (
	"bytes"
	"fmt"
	"os"
	"sort"

	"github.com/dodwmd/companyinacan/core/problem"
)

// Notice renders THIRD_PARTY_LICENSES deterministically (sorted, LF, no dates).
func Notice(entries []Entry) []byte {
	sorted := append([]Entry(nil), entries...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Module.ID < sorted[j].Module.ID })
	var accepted, sa []Entry
	for _, e := range sorted {
		if e.Result.SourceAvailable {
			sa = append(sa, e)
		} else {
			accepted = append(accepted, e)
		}
	}
	var b bytes.Buffer
	b.WriteString("# Third-party licences\n\n")
	b.WriteString("Generated by `can licences --write` from the module manifests. Do not edit by hand.\n\n")
	b.WriteString("## Wrapped applications (accepted licences)\n\n")
	table(&b, accepted)
	b.WriteString("\n## Source-available (opt-in)\n\n")
	table(&b, sa)
	return b.Bytes()
}

func table(b *bytes.Buffer, es []Entry) {
	if len(es) == 0 {
		b.WriteString("_None._\n")
		return
	}
	b.WriteString("| Module | Application | Licence | Upstream |\n|---|---|---|---|\n")
	for _, e := range es {
		lic := e.Module.Provider.Licence
		if e.Module.Provider.LicenceSelected != "" {
			lic += " (selected: " + e.Module.Provider.LicenceSelected + ")"
		}
		fmt.Fprintf(b, "| %s | %s | %s | %s |\n", e.Module.ID, e.Module.Provider.Name, lic, e.Module.Provider.Upstream)
	}
}

// CheckNotice compares the committed notice with the generated one.
func CheckNotice(file string, want []byte) []problem.Problem {
	got, err := os.ReadFile(file) //nolint:gosec // user-provided path
	if err == nil && bytes.Equal(got, want) {
		return nil
	}
	msg := "THIRD_PARTY_LICENSES is out of date; regenerate it with `make licences` (or `can licences --write`)"
	if err != nil {
		msg = "THIRD_PARTY_LICENSES is missing; generate it with `make licences` (or `can licences --write`)"
	}
	return []problem.Problem{{File: file, Rule: "licence.notice-stale", Severity: problem.Error, Message: msg}}
}
