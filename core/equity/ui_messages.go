// msg renders a catalogue entry; a missing key shows the key, so it is visible (tests forbid it).
func (u *UI) msg(key string, args ...any) string {
	s, ok := uiMessagesEN[key]
	if !ok {
		return key
	}
	if len(args) > 0 {
		return fmt.Sprintf(s, args...)
	}
	return s
}
