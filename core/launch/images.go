// Package launch is the part of `can up` that runs after a cluster exists (epic E24): load the
// images, apply the platform manifests, deploy can-core, create the admin, push company.yaml,
// publish the site, route traffic, install the backup timer and wait for readiness.
//
// Every effect goes through a seam (Kube for kubectl, ImageLoader for image import, a provider
// Runner for the host), so the whole sequence is verified offline against fakes and, in CI,
// against a real k3d cluster with the same code.
package launch

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// The three images a company needs after `can up`: the control plane, the site server and the
// forms gateway (the latter is installed through can-core as a module).
const (
	ImageCore   = "can-core"
	ImageStatic = "can-static"
	ImageForms  = "can-forms"
)

// ImageNames lists the images in a fixed order.
var ImageNames = []string{ImageCore, ImageStatic, ImageForms}

// Where an ImageSet came from.
const (
	// SourceRelease: digest-pinned references from deploy/release-images.json; the server pulls them.
	SourceRelease = "release"
	// SourceDir: local tarballs (`make images`) shipped over SSH; no registry is involved.
	SourceDir = "dir"
)

// Image is one container image.
type Image struct {
	Name   string `json:"-"`
	Ref    string `json:"ref"`
	File   string `json:"file,omitempty"`   // tarball name inside the images directory (SourceDir)
	SHA256 string `json:"sha256,omitempty"` // of the tarball (SourceDir)
	path   string
}

// ImageSet is the resolved set of images `can up` deploys.
type ImageSet struct {
	Source  string
	Version string
	Images  map[string]Image
}

// Ref returns the reference to put in manifests for the named image.
func (s ImageSet) Ref(name string) string { return s.Images[name].Ref }

// Upload returns the images that must be shipped to the server (none for a release manifest).
func (s ImageSet) Upload() []Image {
	if s.Source != SourceDir {
		return nil
	}
	var out []Image
	for _, n := range ImageNames {
		out = append(out, s.Images[n])
	}
	return out
}

// Fingerprint identifies the set (refs and tarball checksums) so a re-run can tell whether the
// server already holds exactly these images.
func (s ImageSet) Fingerprint() string {
	h := sha256.New()
	names := make([]string, 0, len(s.Images))
	for n := range s.Images {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		i := s.Images[n]
		fmt.Fprintf(h, "%s|%s|%s\n", n, i.Ref, i.SHA256)
	}
	return hex.EncodeToString(h.Sum(nil))
}

var (
	reDigestRef = regexp.MustCompile(`^[a-z0-9][a-z0-9./_-]{0,200}@sha256:[0-9a-f]{64}$`)
	reLocalRef  = regexp.MustCompile(`^[a-z0-9][a-z0-9./_-]{0,200}(:[A-Za-z0-9._-]{1,128})?$`)
	reTarName   = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._-]{0,100}\.tar$`)
	reHex64     = regexp.MustCompile(`^[0-9a-f]{64}$`)
)

type indexFile struct {
	Schema  int              `json:"schema"`
	Version string           `json:"version"`
	Images  map[string]Image `json:"images"`
}

func readIndex(path string) (*indexFile, error) {
	b, err := os.ReadFile(path) //nolint:gosec // operator-chosen path
	if err != nil {
		return nil, err
	}
	var ix indexFile
	dec := json.NewDecoder(strings.NewReader(string(b)))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&ix); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	if ix.Schema != 1 {
		return nil, fmt.Errorf("%s: schema %d is not supported (want 1)", path, ix.Schema)
	}
	for _, n := range ImageNames {
		if _, ok := ix.Images[n]; !ok {
			return nil, fmt.Errorf("%s: image %q is missing (need %s)", path, n, strings.Join(ImageNames, ", "))
		}
	}
	for n := range ix.Images {
		known := false
		for _, k := range ImageNames {
			known = known || k == n
		}
		if !known {
			return nil, fmt.Errorf("%s: unknown image %q", path, n)
		}
	}
	return &ix, nil
}

// LoadRelease reads a release manifest (deploy/release-images.json, written by the release
// pipeline). Every reference must be pinned by digest: a tag, a placeholder or anything that is
// not repo@sha256:<64 hex> is refused, so nothing mutable ever reaches a production server.
func LoadRelease(path string) (ImageSet, error) {
	ix, err := readIndex(path)
	if err != nil {
		return ImageSet{}, err
	}
	set := ImageSet{Source: SourceRelease, Version: ix.Version, Images: map[string]Image{}}
	for _, n := range ImageNames {
		i := ix.Images[n]
		if !reDigestRef.MatchString(i.Ref) {
			return ImageSet{}, fmt.Errorf("%s: image %s reference %q is not pinned by digest (want repository@sha256:<64 hex>); a release manifest is generated by the release pipeline, not edited by hand", path, n, i.Ref)
		}
		if i.File != "" || i.SHA256 != "" {
			return ImageSet{}, fmt.Errorf("%s: image %s: file and sha256 belong to a local images directory, not a release manifest", path, n)
		}
		i.Name = n
		set.Images[n] = i
	}
	return set, nil
}

// LoadDir reads <dir>/images.json (written by `make images`) and verifies every tarball against
// its recorded sha256 before anything is sent anywhere.
func LoadDir(dir string) (ImageSet, error) {
	idx := filepath.Join(dir, "images.json")
	ix, err := readIndex(idx)
	if errors.Is(err, os.ErrNotExist) {
		return ImageSet{}, fmt.Errorf("%s does not exist: build the images first with `make images` (writes build/images), then pass that directory with --images-from", idx)
	}
	if err != nil {
		return ImageSet{}, err
	}
	set := ImageSet{Source: SourceDir, Version: ix.Version, Images: map[string]Image{}}
	for _, n := range ImageNames {
		i := ix.Images[n]
		i.Name = n
		if !reLocalRef.MatchString(i.Ref) || strings.Contains(i.Ref, "REPLACE_WITH") {
			return ImageSet{}, fmt.Errorf("%s: image %s reference %q is not valid", idx, n, i.Ref)
		}
		if !reTarName.MatchString(i.File) {
			return ImageSet{}, fmt.Errorf("%s: image %s file %q must be a plain .tar file name inside the images directory", idx, n, i.File)
		}
		if !reHex64.MatchString(i.SHA256) {
			return ImageSet{}, fmt.Errorf("%s: image %s sha256 must be 64 lowercase hex characters", idx, n)
		}
		i.path = filepath.Join(dir, i.File)
		got, err := fileSHA256(i.path)
		if err != nil {
			return ImageSet{}, fmt.Errorf("image %s: %w (run `make images` again)", n, err)
		}
		if got != i.SHA256 {
			return ImageSet{}, fmt.Errorf("image %s: tarball %s has sha256 %s but %s records %s; refusing to ship it (rebuild with `make images`)", n, i.File, got, idx, i.SHA256)
		}
		set.Images[n] = i
	}
	return set, nil
}

func fileSHA256(path string) (string, error) {
	f, err := os.Open(path) //nolint:gosec // path built from a validated file name
	if err != nil {
		return "", err
	}
	defer func() { _ = f.Close() }()
	h := sha256.New()
	if _, err := io.Copy(h, f); err != nil {
		return "", err
	}
	return hex.EncodeToString(h.Sum(nil)), nil
}

// Read returns the tarball bytes of a SourceDir image, re-verified against the recorded checksum
// at the moment of use (the file could have changed since LoadDir).
func (i Image) Read() ([]byte, error) {
	b, err := os.ReadFile(i.path)
	if err != nil {
		return nil, err
	}
	h := sha256.Sum256(b)
	if hex.EncodeToString(h[:]) != i.SHA256 {
		return nil, fmt.Errorf("image %s: tarball changed on disk since it was verified", i.Name)
	}
	return b, nil
}

// ImageOptions says where images come from.
type ImageOptions struct {
	FromDir         string // --images-from
	ReleaseManifest string // --release-manifest, or the default deploy/release-images.json when it exists
}

// DefaultReleaseManifest is looked up relative to the working directory when neither flag is given.
const DefaultReleaseManifest = "deploy/release-images.json"

// ResolveImages picks the image source. Giving both is refused as ambiguous; giving neither falls
// back to the release manifest if the checkout has one, and otherwise fails closed with both ways
// to get images.
func ResolveImages(o ImageOptions) (ImageSet, error) {
	switch {
	case o.FromDir != "" && o.ReleaseManifest != "":
		return ImageSet{}, errors.New("--images-from and --release-manifest are alternatives: use the tarballs from `make images`, or the digests from a release manifest, not both")
	case o.FromDir != "":
		return LoadDir(o.FromDir)
	case o.ReleaseManifest != "":
		return LoadRelease(o.ReleaseManifest)
	}
	if _, err := os.Stat(DefaultReleaseManifest); err == nil {
		return LoadRelease(DefaultReleaseManifest)
	}
	return ImageSet{}, errors.New("no container images to deploy: from a source checkout run `make images` and then `make up IMAGES_FROM=build/images` (or `can up --images-from build/images`); " +
		"from a release use `--release-manifest deploy/release-images.json`, which pins every image by digest. See docs/make-up.md, \"Getting the images\"")
}
