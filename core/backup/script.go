package backup

import (
	"bytes"
	"fmt"
	"strings"
	"text/template"
)

// File names.
const (
	MarkerName   = "COMPLETE"        // in the dumps dir, written by can-core
	ManifestName = "MANIFEST.sha256" // in the host state dir, written by the script
	LedgerCopy   = "erasure-ledger.jsonl"
	MarkerCopy   = "COMPLETE" // copy of the marker the backup ran under, in the host state dir
	// Credential files under Settings.ConfigDir.
	EnvFileName      = "restic.env"
	PasswordFileName = "restic.password"
	WebhookFileName  = "webhook.url"
)

// Exit codes of the backup script (documented in docs/backup-restore.md).
const (
	ExitMarkerMissing = 10
	ExitMarkerStale   = 11
	ExitLocked        = 12
	ExitUnsafeDumps   = 13
	ExitBackupFailed  = 20
	ExitForgetFailed  = 21
	ExitLedgerFailed  = 22
)

// LedgerOnlyArg makes the script sync the erasure ledger and nothing else (the frequent timer).
const LedgerOnlyArg = "--ledger-only"

// shq single-quotes s for POSIX shells.
func shq(s string) string { return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'" }

var scriptTmpl = template.Must(template.New("backup.sh").Funcs(template.FuncMap{"q": shq}).Parse(`#!/usr/bin/env bash
# Generated by can (epic E08). Do not edit; regenerate with: can backup install
#
# Runs restic over the dumps can-core produced. Exit codes:
#   0 ok  10 marker missing  11 marker stale or changed during the backup  12 lock held
#   13 unsafe dumps/state directory or ledger (symlink, wrong owner, world-writable)
#   20 restic backup failed  21 forget/prune failed  22 erasure ledger import or upload failed
# With --ledger-only it stops after the erasure ledger (can-erasure-sync.timer).
# If both a backup failure and a ledger failure happen, the backup code wins; the ledger is
# always synced first and independently, so erasures are uploaded even when the backup fails.
# Failures are written to the journal (tag can-backup) and, if {{.Webhook}} exists, POSTed there.
set -Eeuo pipefail
umask 077

DUMPS={{q .DumpsDir}}
STATE={{q .StateDir}}
HOSTSTATE={{q .HostStateDir}}
K3S={{q .K3sDir}}
LEDGER={{q .LedgerSource}}
MAX_AGE={{.MaxAge}}
RUN_ID=""
main_rc=0
ledger_rc=0
LEDGER_ONLY=0
if [ "${1:-}" = {{q .LedgerOnlyArg}} ]; then LEDGER_ONLY=1; fi

log() { logger -t can-backup -p user.info -- "$*" || true; echo "can-backup: $*"; }

json_escape() {
  local s=${1//\\/\\\\}
  s=${s//\"/\\\"}
  printf '%s' "$s" | tr '\n\r\t' '   ' | tr -d '\000-\010\013\014\016-\037'
}

notify() {
  [ -s {{q .Webhook}} ] || return 0
  # The URL is a secret: it goes to curl on stdin (-K -), never on the command line.
  { printf 'url = "%s"\n' "$(tr -d '"\\\n' <{{q .Webhook}})"; } |
    curl -fsS -m 10 -K - -X POST -H 'Content-Type: application/json' \
      --data "{\"text\":\"can-backup $(json_escape "$1")\"}" >/dev/null 2>&1 || true
}

# A warning does not fail the run: it is logged and sent to the same webhook.
warn() {
  logger -t can-backup -p user.warning -- "WARNING: $1" || true
  echo "can-backup: WARNING: $1" >&2
  notify "warning: $1"
}

# The frequent ledger sync would send the same webhook every quarter of an hour: it sends each
# message once, again after a day, and again when it returns after a run that succeeded.
ALERTS={{q .StateDir}}/ledger-alerts

report() {
  logger -t can-backup -p user.err -- "FAILED($1): $2" || true
  echo "can-backup: FAILED($1): $2" >&2
  if [ "$LEDGER_ONLY" -eq 1 ]; then
    [ -z "$(find "$ALERTS" -mmin +1440 2>/dev/null)" ] || rm -f "$ALERTS"
    if grep -qxF -- "($1) $2" "$ALERTS" 2>/dev/null; then return 0; fi
    printf '%s\n' "($1) $2" >>"$ALERTS" || true
  fi
  notify "failed: ($1) $2"
}

finish() {
  if [ "$main_rc" -ne 0 ]; then exit "$main_rc"; fi
  exit "$ledger_rc"
}

fail() {
  local code=$1; shift
  report "$code" "$*"
  trap - ERR
  main_rc=$code
  finish
}
trap 'fail 1 "unexpected error near line $LINENO"' ERR

# A directory we write as root must be owned by us and not group/other-writable. These checks
# are not atomic: a path can change between check and use, which is why the directories are
# private to root and nothing here follows links that can-core controls.
safe_dir() {
  if [ -e "$1" ] || [ -L "$1" ]; then
    [ -d "$1" ] && [ ! -L "$1" ] || fail 13 "$1 is not a plain directory"
    [ "$(stat -c %u "$1")" = "$(id -u)" ] || fail 13 "$1 is not owned by uid $(id -u)"
    [ -z "$(find "$1" -maxdepth 0 -perm /022)" ] || fail 13 "$1 is group- or other-writable"
  fi
  if [ "$(id -u)" -eq 0 ]; then install -d -o root -g root -m 0700 "$1"; else install -d -m 0700 "$1"; fi
}

# State dir and lock: one run at a time.
safe_dir "$STATE"
if [ "$LEDGER_ONLY" -eq 0 ]; then
  exec 9>"$STATE/backup.lock"
  flock -n 9 || fail 12 "another backup run holds the lock"
fi

# Credentials come from root-only files, never from the unit or the command line.
ENVFILE={{q .EnvPath}}
[ -r "$ENVFILE" ] || fail 1 "missing $ENVFILE"
set -a
# shellcheck disable=SC1090
. "$ENVFILE"
set +a
export RESTIC_REPOSITORY={{q .Repository}}
export RESTIC_PASSWORD_FILE={{q .PasswordPath}}
export RESTIC_CACHE_DIR="${CACHE_DIRECTORY:-$STATE/restic-cache}"
[ -r "$RESTIC_PASSWORD_FILE" ] || fail 1 "missing $RESTIC_PASSWORD_FILE"

# Host state lives in a root-owned directory outside the dumps dir that can-core can write to.
safe_dir "$HOSTSTATE"

# Erasure ledger first and independently of the backup: a failed backup must not hold back erasures.
# One ledger run at a time: the nightly backup and the frequent sync both do this part.
exec 8>"$STATE/ledger.lock"
flock -w 600 8 || fail 12 "another run holds the erasure ledger lock"

# What can-core collected from the modules goes into the ledger first. Not when the ledger vanished:
# making a new one would hide that.
COLLECTED="$DUMPS/{{.CollectedDir}}"
if [ -e "$COLLECTED" ] && [ ! -L "$LEDGER" ] && { [ -e "$LEDGER" ] || [ ! -s "$HOSTSTATE/{{.LedgerCopy}}" ]; }; then
  if [ -x {{q .CanBin}} ]; then
    if ! {{q .CanBin}} backup --help 2>/dev/null | grep ledger-import >/dev/null; then
      ledger_rc=22
      report 22 "{{.CanBin}} is too old (it has no ledger-import): update it to this release; erasures do NOT reach the bucket"
    elif ! {{q .CanBin}} backup ledger-import --from "$COLLECTED" --ledger "$LEDGER"; then
      ledger_rc=22
      report 22 "erasures collected by can-core are missing from the ledger (journalctl -t can-backup and the unit's journal say why)"
    fi
  elif [ -s "$COLLECTED/{{.CollectedLedger}}" ]; then
    ledger_rc=22
    report 22 "there are erasures to record but {{.CanBin}} is not installed: they do NOT reach the bucket, and a restore would bring the erased data back"
  else
    log "{{.CanBin}} is not installed: erasures will not reach the bucket"
  fi
fi

if [ -L "$LEDGER" ]; then
  fail 13 "erasure ledger $LEDGER is a symlink"
elif [ -f "$LEDGER" ]; then
  cp -f -- "$LEDGER" "$HOSTSTATE/{{.LedgerCopy}}"
  if [ -s "$LEDGER" ] && ! {{q .CanBin}} backup ledger-sync --ledger "$LEDGER" --repo "$RESTIC_REPOSITORY" --password-file "$RESTIC_PASSWORD_FILE" --env-file "$ENVFILE"; then
    ledger_rc=22
    report 22 "erasure ledger upload failed"
  fi
elif [ -e "$LEDGER" ]; then
  ledger_rc=22
  report 22 "erasure ledger $LEDGER is not a regular file"
elif [ -s "$HOSTSTATE/{{.LedgerCopy}}" ]; then
  # We saw a ledger on an earlier run and it is gone: erasures must not silently disappear.
  ledger_rc=22
  report 22 "erasure ledger $LEDGER vanished (a copy from an earlier run is kept in $HOSTSTATE)"
fi
exec 8>&-
if [ "$LEDGER_ONLY" -eq 1 ]; then
  if [ "$ledger_rc" -eq 0 ]; then rm -f "$ALERTS"; fi
  finish
fi

# The dumps dir is writable by can-core; refuse anything a root script could be tricked by.
[ -d "$DUMPS" ] && [ ! -L "$DUMPS" ] || fail 10 "dumps directory $DUMPS is missing"
[ -z "$(find "$DUMPS" -maxdepth 0 -perm -0002)" ] || fail 13 "$DUMPS is world-writable"
[ -z "$(find "$DUMPS" -type l -print -quit)" ] || fail 13 "symlink found inside $DUMPS"

# Completion marker: can-core deletes it at the start of a dump run and writes it at the end.
MARKER="$DUMPS/{{.Marker}}"
[ -f "$MARKER" ] || fail 10 "completion marker $MARKER is missing: can-core has not finished a dump run"
cp -f -- "$MARKER" "$HOSTSTATE/{{.MarkerCopy}}"
marker_field() { sed -n "s/^$1=//p" "$2" 2>/dev/null | head -n 1 || true; }
RUN_ID=$(marker_field run_id "$HOSTSTATE/{{.MarkerCopy}}")
FINISHED=$(marker_field finished_at "$HOSTSTATE/{{.MarkerCopy}}")
case "$FINISHED" in ''|*[!0-9]*) fail 11 "completion marker has no valid finished_at" ;; esac
[ -n "$RUN_ID" ] || fail 11 "completion marker has no run_id"
NOW=$(date +%s)
if [ $((NOW - FINISHED)) -gt "$MAX_AGE" ]; then
  fail 11 "completion marker (run $RUN_ID) is older than $((MAX_AGE / 3600))h"
fi

# Host-level state: consistent copy of the k3s SQLite datastore, node token, secrets-encryption key.
if [ -f "$K3S/server/db/state.db" ]; then
  rm -f "$HOSTSTATE/k3s-state.db"
  sqlite3 "$K3S/server/db/state.db" ".backup '$HOSTSTATE/k3s-state.db'"
fi
for f in server/token server/cred/encryption-config.json; do
  if [ -f "$K3S/$f" ]; then cp -p "$K3S/$f" "$HOSTSTATE/$(basename "$f")"; fi
done

# Manifest of every dump file, so 'can backup verify' and restore can compare hashes.
# Dot entries are can-core's staging directories and temporaries: not part of the dumps.
(cd "$DUMPS" && find . -mindepth 1 -name '.*' -prune -o -type f ! -name {{q .Marker}} -print0 | sort -z | xargs -0 -r sha256sum) >"$HOSTSTATE/{{.Manifest}}.tmp"
mv "$HOSTSTATE/{{.Manifest}}.tmp" "$HOSTSTATE/{{.Manifest}}"

# Raw SQLite files are left out only for modules whose dump is in this run; a module that was
# not dumped (added later, or without data then) keeps its raw files.
PVCROOT={{q .PVCRoot}}
EXCLUDES=()
if [ -f "$DUMPS/{{.DumpedList}}" ]; then
  while read -r mod db; do
    [[ "$mod" =~ ^[a-z][a-z0-9-]*$ && "$db" == sqlite ]] || continue
    for pat in {{range .SQLite}}{{q .}} {{end}}; do
      EXCLUDES+=(--exclude "$PVCROOT/pvc-*_mod-${mod}_*/**/$pat")
    done
  done <"$DUMPS/{{.DumpedList}}"
fi

rm -f "$HOSTSTATE/{{.AlertsName}}"
if [ -f "$DUMPS/{{.AlertsName}}" ]; then cp -f -- "$DUMPS/{{.AlertsName}}" "$HOSTSTATE/{{.AlertsName}}"; fi

# Remove only stale restic locks (restic refuses to remove a live one).
restic unlock || log "restic unlock failed (continuing)"

ATTEMPT="$(date +%s)-$$"
log "backup starting (run $RUN_ID, attempt $ATTEMPT)"
brc=0
restic backup --tag can --tag "run-$RUN_ID" --tag "attempt-$ATTEMPT" \
  --exclude "$DUMPS/.*" --exclude "$DUMPS/**/.*" \
  ${EXCLUDES[@]+"${EXCLUDES[@]}"} \
{{- range .Excludes}}
  --exclude {{q .}} \
{{- end}}
  {{range .Sources}}{{q .}} {{end}}|| brc=$?
case "$brc" in
  0) ;;
  3) log "restic reported unreadable or vanished files (exit 3); the snapshot was created" ;;
  *) fail 20 "restic backup failed (exit $brc)" ;;
esac

# can-core must not have started a new dump run while we were reading the dumps.
if [ "$(marker_field run_id "$MARKER")" != "$RUN_ID" ] || [ "$(marker_field finished_at "$MARKER")" != "$FINISHED" ]; then
  restic tag --tag "attempt-$ATTEMPT" --add inconsistent || true
  fail 11 "completion marker changed during the backup; snapshot attempt-$ATTEMPT tagged inconsistent"
fi

# --group-by '' : every snapshot ages out on its own, including those from a previous host or paths.
restic forget --group-by '' --keep-within {{.RetentionDays}}d --prune --tag can || fail 21 "restic forget/prune failed"

printf 'run_id=%s\nfinished_at=%s\n' "$RUN_ID" "$(date +%s)" >"$STATE/backup-status.tmp"
mv "$STATE/backup-status.tmp" "$STATE/backup-status"
# Databases (or vanished data) that this backup does not hold, as can-core reported them.
if [ -f "$HOSTSTATE/{{.AlertsName}}" ]; then
  while IFS= read -r alert; do
    [ -n "$alert" ] && warn "$alert"
  done < <(head -n 20 "$HOSTSTATE/{{.AlertsName}}" | cut -c1-400)
fi
log "backup complete (run $RUN_ID)"
finish
`))

type scriptData struct {
	Settings
	MaxAge                                 int
	Webhook, EnvPath, PasswordPath, Marker string
	Manifest, LedgerCopy, MarkerCopy       string
	CollectedDir, CollectedLedger          string
	LedgerOnlyArg                          string
	Excludes, Sources, SQLite              []string
	DumpedList, AlertsName                 string
}

// GenerateScript renders the host backup script for plan p.
func GenerateScript(p *Plan, s Settings) string {
	d := scriptData{
		Settings: s, MaxAge: int(s.MaxMarkerAge.Seconds()),
		Webhook: s.ConfigDir + "/" + WebhookFileName, EnvPath: s.ConfigDir + "/" + EnvFileName, PasswordPath: s.ConfigDir + "/" + PasswordFileName,
		Marker: MarkerName, Manifest: ManifestName, LedgerCopy: LedgerCopy, MarkerCopy: MarkerCopy, CollectedDir: CollectedDir, CollectedLedger: CollectedLedger, LedgerOnlyArg: LedgerOnlyArg,
		Excludes: p.Excludes, Sources: p.Sources, SQLite: sqliteExcludes, DumpedList: DumpedList, AlertsName: AlertsName,
	}
	var b bytes.Buffer
	if err := scriptTmpl.Execute(&b, d); err != nil {
		panic(fmt.Sprintf("backup: script template: %v", err)) // template is static; unreachable
	}
	return b.String()
}

// GenerateService renders can-backup.service. Credentials are read by the script
// from files; the unit carries none.
func GenerateService(s Settings) string {
	return fmt.Sprintf(`[Unit]
Description=Company in a Can backup (restic)
Documentation=https://github.com/dodwmd/companyinacan/blob/main/docs/backup-restore.md
After=network-online.target k3s.service
Wants=network-online.target
OnFailure=can-backup-failure.service

[Service]
Type=oneshot
ExecStart=%s
TimeoutStartSec=6h
Nice=10
IOSchedulingClass=idle
CacheDirectory=can-backup
PrivateTmp=true
ProtectHome=true
ProtectSystem=strict
ReadWritePaths=%s %s -%s/server/db
NoNewPrivileges=true
`, s.ScriptPath, s.StateDir, s.DumpsDir, s.K3sDir)
}

// GenerateFailureService renders can-backup-failure.service, started by OnFailure=
// so a failed run is visible in the journal even if the webhook is unreachable.
func GenerateFailureService() string {
	return `[Unit]
Description=Company in a Can backup failed

[Service]
Type=oneshot
ExecStart=/usr/bin/logger -t can-backup -p user.crit "can-backup.service failed; see: journalctl -u can-backup.service"
`
}

// GenerateTimer renders can-backup.timer.
func GenerateTimer(s Settings) string {
	return fmt.Sprintf(`[Unit]
Description=Nightly Company in a Can backup, after can-core has produced its dumps

[Timer]
OnCalendar=%s
RandomizedDelaySec=%s
Persistent=true
Unit=can-backup.service

[Install]
WantedBy=timers.target
`, s.Schedule, s.RandomDelay)
}

