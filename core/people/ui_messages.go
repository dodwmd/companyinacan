// msg looks a message up; an unknown key is shown as the key itself (and caught by the test).
func (u *UI) msg(key string, args ...any) string {
	s, ok := uiMessagesEN[key]
	if !ok {
		return key
	}
	if len(args) == 0 {
		return s
	}
	return fmt.Sprintf(s, args...)
}

// flashMsg maps the ?ok= query value to a message; only catalogue keys are accepted, so the query
// cannot inject text.
func flashMsg(u *UI, key string) string {
	if key == "" {
		return ""
	}
	if _, ok := uiMessagesEN["flash."+key]; !ok {
		return ""
	}
	return u.msg("flash." + key)
}
